import { useEffect, useRef, useState } from "react";
import { Bot, Send, Trash2, User } from "lucide-react";
import { api, type AssistantReply, type ChatMessage, type Status } from "../api";
import { ErrorBox, Markdown, Note, SafetyPanel, Spinner } from "../components";
import { SourceList } from "./AnalysisView";

const SUGGESTIONS = [
  "How can I wind down before sleep when my mind is racing?",
  "I have three exams next week. How can I make revision feel manageable?",
  "What are some small things I can do on a stressful workday?",
  "When should I think about talking to a professional?",
];

type Msg = { role: "user" | "assistant"; content: string; reply?: AssistantReply; stored?: ChatMessage };

export default function AssistantPage({ status }: { status: Status | null }) {
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [input, setInput] = useState("");
  const [ctx, setCtx] = useState(true);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState<unknown>(null);
  const end = useRef<HTMLDivElement>(null);

  useEffect(() => {
    api.chatHistory().then((h) => setMsgs(h.map((m) => ({ role: m.role, content: m.content, stored: m })))).catch(() => {});
  }, []);
  useEffect(() => { end.current?.scrollIntoView({ behavior: "smooth" }); }, [msgs, busy]);

  const send = async (text: string) => {
    if (!text.trim()) return;
    setMsgs((m) => [...m, { role: "user", content: text }]); setInput(""); setBusy(true); setErr(null);
    try {
      const r = await api.chat(text, ctx);
      setMsgs((m) => [...m, { role: "assistant", content: r.answer, reply: r }]);
    } catch (e) { setErr(e); } finally { setBusy(false); }
  };
  const clear = async () => { await api.clearChat(); setMsgs([]); };

  return (
    <div className="flex h-[calc(100vh-9.5rem)] min-h-[520px] flex-col gap-4">
      <header className="flex flex-wrap items-end justify-between gap-3">
        <div>
          <h1 className="h1">Reflect</h1>
          <p className="muted">A retrieval-augmented assistant grounded in a curated wellbeing knowledge base (NHS, WHO, NIMH, CDC, APA, Mind).</p>
        </div>
        <div className="flex items-center gap-3">
          <label className="flex items-center gap-2 text-xs text-stone-600">
            <input type="checkbox" checked={ctx} onChange={(e) => setCtx(e.target.checked)} /> Use my recent journal patterns
          </label>
          <button className="btn-ghost !py-1.5" onClick={clear}><Trash2 className="h-4 w-4" /> Clear</button>
        </div>
      </header>
      {status && !status.llm.configured && (
        <Note tone="warn">{status.llm.detail ?? "No LLM configured."} Answers will show the most relevant retrieved passages instead of generated text.</Note>
      )}

      <div className="card flex-1 space-y-4 overflow-y-auto">
        {msgs.length === 0 && (
          <div className="space-y-3">
            <p className="muted">Ask about stress, sleep, routines, study pressure, journaling, or where to find support. Try:</p>
            <div className="grid gap-2 sm:grid-cols-2">
              {SUGGESTIONS.map((s) => <button key={s} onClick={() => send(s)} className="rounded-3xl bg-sand-50 px-4 py-3.5 text-left text-sm text-stone-600 transition hover:-translate-y-0.5 hover:bg-sage-50 hover:text-sage-800">{s}</button>)}
            </div>
          </div>
        )}
        {msgs.map((m, i) => (
          <div key={i} className={`flex gap-3 ${m.role === "user" ? "justify-end" : ""}`}>
            {m.role === "assistant" && <div className="h-8 w-8 shrink-0 rounded-full bg-sage-100 p-1.5 text-sage-600"><Bot className="h-5 w-5" /></div>}
            <div className={`max-w-[85%] space-y-2 rounded-2xl px-4 py-3 ${m.role === "user" ? "bg-sage-600 text-white" : "bg-stone-50"}`}>
              {m.role === "user" ? <p className="whitespace-pre-wrap text-sm">{m.content}</p> : (
                <>
                  {m.reply?.safety && <SafetyPanel safety={m.reply.safety} />}
                  {m.reply?.mode !== "safety" && <Markdown text={m.content} />}
                  <div className="text-[11px] text-stone-400">
                    {m.reply ? (m.reply.mode === "llm" ? `Generated by ${m.reply.provider?.provider} · ${m.reply.provider?.model}` : m.reply.mode === "safety" ? "Safety response (no generation)" : "Retrieval-only (no LLM)")
                      : m.stored?.provider ? `mode: ${m.stored.provider}` : ""}
                    {m.reply?.guardrail_removed.length ? " · safety filter applied" : ""}
                  </div>
                  {(m.reply?.sources ?? m.stored?.sources ?? []).length > 0 && <SourceList sources={m.reply?.sources ?? m.stored?.sources ?? []} />}
                </>
              )}
            </div>
            {m.role === "user" && <div className="h-8 w-8 shrink-0 rounded-full bg-stone-200 p-1.5 text-stone-600"><User className="h-5 w-5" /></div>}
          </div>
        ))}
        {busy && <Spinner label="Retrieving passages and generating..." />}
        <ErrorBox error={err} />
        <div ref={end} />
      </div>

      <form className="flex gap-2" onSubmit={(e) => { e.preventDefault(); send(input); }}>
        <input className="input" placeholder="Ask something..." value={input} onChange={(e) => setInput(e.target.value)} maxLength={4000} />
        <button className="btn-primary" disabled={busy || !input.trim()}><Send className="h-4 w-4" /></button>
      </form>
    </div>
  );
}
